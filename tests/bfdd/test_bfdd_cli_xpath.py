import frrtest


class TestBfddCliXpath(frrtest.TestMultiOut):
    program = "./test_bfdd_cli_xpath"


TestBfddCliXpath.okfail("peer")
TestBfddCliXpath.okfail("no peer")
TestBfddCliXpath.okfail("sbfd-echo peer")
TestBfddCliXpath.okfail("no sbfd-echo peer")
TestBfddCliXpath.okfail("sbfd-init peer with srv6")
TestBfddCliXpath.okfail("no sbfd-init peer with srv6")
TestBfddCliXpath.okfail("sbfd-init peer")
TestBfddCliXpath.okfail("no sbfd-init peer")
TestBfddCliXpath.okfail("peer, interface name of 1100 bytes")
TestBfddCliXpath.okfail("peer, vrf name of 1100 bytes")
TestBfddCliXpath.okfail("no peer, interface name of 1100 bytes")
TestBfddCliXpath.okfail("sbfd-echo, bfd name of 1100 bytes")
TestBfddCliXpath.okfail("no sbfd-echo, bfd name of 1100 bytes")
TestBfddCliXpath.okfail("sbfd-init srv6, bfd name of 1100 bytes")
TestBfddCliXpath.okfail("no sbfd-init srv6, bfd name of 1100 bytes")
TestBfddCliXpath.okfail("sbfd-init, bfd name of 1100 bytes")
TestBfddCliXpath.okfail("no sbfd-init, bfd name of 1100 bytes")
TestBfddCliXpath.okfail("peer, interface name of IFNAMSIZ - 1")
TestBfddCliXpath.okfail("peer, interface name of IFNAMSIZ")
TestBfddCliXpath.okfail("peer, vrf name of VRF_NAMSIZ")
TestBfddCliXpath.okfail("peer, vrf name of VRF_NAMSIZ + 1")
TestBfddCliXpath.okfail("no peer, interface name of IFNAMSIZ - 1")
TestBfddCliXpath.okfail("no peer, interface name of IFNAMSIZ")
TestBfddCliXpath.okfail("no peer, vrf name of VRF_NAMSIZ")
TestBfddCliXpath.okfail("no peer, vrf name of VRF_NAMSIZ + 1")
TestBfddCliXpath.okfail("sbfd-echo, bfd name of BFD_NAME_SIZE")
TestBfddCliXpath.okfail("sbfd-echo, bfd name of BFD_NAME_SIZE + 1")
TestBfddCliXpath.okfail("no sbfd-echo, bfd name of BFD_NAME_SIZE")
TestBfddCliXpath.okfail("no sbfd-echo, bfd name of BFD_NAME_SIZE + 1")
TestBfddCliXpath.okfail("sbfd-init srv6, bfd name of BFD_NAME_SIZE")
TestBfddCliXpath.okfail("sbfd-init srv6, bfd name of BFD_NAME_SIZE + 1")
TestBfddCliXpath.okfail("no sbfd-init srv6, bfd name of BFD_NAME_SIZE")
TestBfddCliXpath.okfail("no sbfd-init srv6, bfd name of BFD_NAME_SIZE + 1")
TestBfddCliXpath.okfail("sbfd-init, bfd name of BFD_NAME_SIZE")
TestBfddCliXpath.okfail("sbfd-init, bfd name of BFD_NAME_SIZE + 1")
TestBfddCliXpath.okfail("sbfd-init, vrf name of VRF_NAMSIZ")
TestBfddCliXpath.okfail("sbfd-init, vrf name of VRF_NAMSIZ + 1")
TestBfddCliXpath.okfail("no sbfd-init, bfd name of BFD_NAME_SIZE")
TestBfddCliXpath.okfail("no sbfd-init, bfd name of BFD_NAME_SIZE + 1")
TestBfddCliXpath.okfail("peer, longest interface and vrf names")
TestBfddCliXpath.okfail("sbfd-init srv6, longest addresses, bfd and vrf names")
