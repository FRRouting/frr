"""Scale regression for batched VRF EVPN route-target reloads.

Topology (single node; no BGP peers; reload-path coverage only):

    r1-eth0 ---[sw1]
       |
    vrf_shared1  table 10  L3VNI 20001
      172.16.1.3/24
      vxlan20001 (id 20001, local 1.1.1.2) master brl3
      1,200 IPv4 /32 static routes via 172.16.1.10
      advertised as EVPN Type-5 (advertise ipv4 unicast)

Key config (generated by ``_config()``):

    vrf vrf_shared1
     ip route 198.18.0.0/32 172.16.1.10
     ... 1,200 static routes, through 198.18.4.175/32 ...
     vni 20001
    !
    router bgp 4200000102 vrf vrf_shared1
     address-family ipv4 unicast
      redistribute static
     address-family l2vpn evpn
      advertise ipv4 unicast route-map SVC_EXPORT
      route-target import 60005:102011 ...   # 1,536 RTs, 3 ASNs x 512

The static routes are redistributed and exported as Type-5 so a bulk import-RT
delete walks a scaled EVPN table, not an empty one.  Startup has those Type-5s
and no import RTs.  The test adds the RT set through ``frr-reload.py --reload``,
then rolls it back in one VRF EVPN AF batch.
"""

import ipaddress
import os
import sys

import pytest

CWD = os.path.dirname(os.path.realpath(__file__))
sys.path.append(os.path.join(CWD, ".."))

from lib import topotest
from lib.evpn import evpn_plumb_l3vni, evpn_rt_config_lines, evpn_scale_rt_list
from lib.topogen import Topogen
from lib.topotest import iproute2_is_vrf_capable
from lib.common_config import required_linux_kernel_version

import frr_reload_lib as f_reload

pytestmark = [pytest.mark.bgpd, pytest.mark.staticd, pytest.mark.evpn]

# Daemon names for load_frr_config (strings, not RD_* ints — bare ints are
# unpacked as (daemon, param) tuples and raise TypeError).
NEEDED_DAEMONS = ["zebra", "mgmtd", "staticd", "bgpd"]

AS_NUM = 4200000102
VRF = "vrf_shared1"
VRF_TABLE = 10
L3VNI = 20001
VTEP_IP = "1.1.1.2"
STATIC_ROUTE_COUNT = 1200
IMPORT_RTS = evpn_scale_rt_list()
IMPORT_RT_COUNT = len(IMPORT_RTS)
RELOAD_TIMEOUT = float(os.environ.get("FRR_RELOAD_RT_TIMEOUT", "120"))


def _static_routes():
    first = int(ipaddress.IPv4Address("198.18.0.0"))
    return [
        "ip route {}/32 172.16.1.10".format(ipaddress.IPv4Address(first + offset))
        for offset in range(STATIC_ROUTE_COUNT)
    ]


def _import_rts():
    return IMPORT_RTS


def _config(include_import_rts):
    lines = [
        "frr defaults datacenter",
        "hostname r1",
        "!",
        "vrf {}".format(VRF),
    ]
    lines.extend(" " + route for route in _static_routes())
    lines.extend(
        [
            " vni {}".format(L3VNI),
            "exit-vrf",
            "!",
            # Addresses must live in FRR config. A raw "ip addr add" on a
            # munet-managed veth is wiped at start_router(); without
            # 172.16.1.3/24 the 1,200 statics via 172.16.1.10 stay inactive
            # and advertise ipv4 unicast originates no Type-5s.
            "interface lo",
            " ip address {}/32".format(VTEP_IP),
            "exit",
            "!",
            "interface r1-eth0 vrf {}".format(VRF),
            " ip address 172.16.1.3/24",
            "exit",
            "!",
            "router bgp {}".format(AS_NUM),
            " bgp router-id {}".format(VTEP_IP),
            " no bgp default ipv4-unicast",
            " address-family l2vpn evpn",
            "  advertise-all-vni",
            " exit-address-family",
            "exit",
            "!",
            "router bgp {} vrf {}".format(AS_NUM, VRF),
            " bgp router-id {}".format(VTEP_IP),
            " no bgp default ipv4-unicast",
            " address-family ipv4 unicast",
            "  redistribute connected",
            "  redistribute static",
            " exit-address-family",
            " address-family ipv6 unicast",
            " exit-address-family",
            " address-family l2vpn evpn",
            "  advertise ipv4 unicast route-map SVC_EXPORT",
            "  advertise ipv6 unicast route-map SVC_EXPORT",
        ]
    )
    if include_import_rts:
        lines.extend(evpn_rt_config_lines("import", _import_rts(), indent="  "))
    lines.extend(
        [
            " exit-address-family",
            "exit",
            "!",
            "ip prefix-list SVC_SVC_PREFIXES seq 10 permit 172.16.1.0/24",
            "ip prefix-list SVC_SVC_PREFIXES seq 20 permit 198.18.0.0/16 le 32",
            "route-map SVC_EXPORT permit 10",
            " match ip address prefix-list SVC_SVC_PREFIXES",
            "exit",
            "!",
        ]
    )
    return lines


def _running_counts(router):
    lines = [line.strip() for line in f_reload.running_config(router).splitlines()]
    return (
        sum(line.startswith("ip route 198.18.") for line in lines),
        sum(line.startswith("route-target import ") for line in lines),
    )


def _type5_count(router):
    """Local Type-5 prefixes in the EVPN table (the table import-RT unmap walks)."""
    out = router.vtysh_cmd("show bgp l2vpn evpn route type prefix") or ""
    # Match installed NLRI, not the "[5]:[EthTag]:..." legend line.
    return sum(1 for line in out.splitlines() if "[5]:[0]:" in line)


def _wait_type5(router, minimum):
    def _check():
        got = _type5_count(router)
        if got >= minimum:
            return None
        sample = (router.vtysh_cmd("show bgp l2vpn evpn route type prefix") or "")[:500]
        return "type-5 count {} want >= {}; show:\n{}".format(got, minimum, sample)

    _, result = topotest.run_and_expect(_check, None, count=60, wait=1)
    assert result is None, result


@pytest.fixture(scope="module")
def tgen(request):
    def build(tg):
        tg.add_router("r1")
        switch = tg.add_switch("sw1")
        switch.add_link(tg.gears["r1"])

    tg = Topogen(build, request.module.__name__)
    tg.start_topology()

    if not iproute2_is_vrf_capable():
        pytest.skip("iproute2 is not VRF capable")
    if required_linux_kernel_version("4.19") is not True:
        pytest.skip("Kernel >= 4.19 required for EVPN L3VNI")

    r1 = tg.gears["r1"]
    # VTEP must exist before the VXLAN device is created.
    r1.cmd_raises("ip addr add {}/32 dev lo".format(VTEP_IP))
    evpn_plumb_l3vni(r1, VRF, VRF_TABLE, L3VNI, VTEP_IP)
    r1.cmd_raises("ip link set dev r1-eth0 master {}".format(VRF))
    r1.cmd_raises("ip link set dev r1-eth0 up")

    # Start with Type-5 static routes and no import RTs so the test can add
    # and then roll back the RT set through frr-reload.py --reload.
    startup = os.path.join(tg.logdir, "r1", "startup.conf")
    os.makedirs(os.path.dirname(startup), exist_ok=True)
    f_reload.write_conf(startup, _config(include_import_rts=False))
    r1.load_frr_config(startup, daemons=NEEDED_DAEMONS)
    tg.start_router()

    yield tg
    tg.stop_topology()


def test_field_scale_import_rt_rollback(tgen):
    """Apply 1,536 RTs, then remove them while retaining 1,200 Type-5 routes."""
    if tgen.routers_have_failure():
        pytest.skip(tgen.errors)

    r1 = tgen.gears["r1"]
    target = os.path.join(tgen.logdir, "r1", "reload-target.conf")

    # Type-5s must exist before the RT reload so a packing/delete bug cannot
    # be confused with origination never coming up.
    _wait_type5(r1, STATIC_ROUTE_COUNT)

    # Add the field-scale RT set through the same packed add path used for
    # rollback recovery, then prove every RT, static route, and Type-5 landed.
    f_reload.apply_and_verify(r1, target, _config(include_import_rts=True))
    assert _running_counts(r1) == (STATIC_ROUTE_COUNT, IMPORT_RT_COUNT)
    _wait_type5(r1, STATIC_ROUTE_COUNT)

    # Removing only the RTs reproduces the bulk-delete delta against a scaled
    # EVPN table.  expect_vrf_batch=True rejects the old per-line fallback even
    # if 1,536 individual vtysh calls happen to finish inside the wall-clock
    # budget.
    result = f_reload.apply_and_verify(
        r1,
        target,
        _config(include_import_rts=False),
        expect_vrf_batch=True,
        max_seconds=RELOAD_TIMEOUT,
    )
    assert _running_counts(r1) == (STATIC_ROUTE_COUNT, 0)
    _wait_type5(r1, STATIC_ROUTE_COUNT)
    assert "vtysh (exec file) exited with status 2" not in result.output


if __name__ == "__main__":
    sys.exit(pytest.main(["-s", "-v"] + sys.argv[1:]))
